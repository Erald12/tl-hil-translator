def iter_entries():
    """Yield dicts: tagalog, hiligaynon, category, note, confidence ('normal' | 'low')."""
    category = "general"
    for raw in RAW.strip().splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.startswith("##"):
            category = line.lstrip("#").strip()
            continue
        if " = " not in line:
            raise ValueError(f"Bad line (missing ' = '): {raw!r}")
        tgl, hil = (p.strip() for p in line.split(" = ", 1))
        confidence = "normal"
        if hil.endswith(" ?"):
            hil, confidence = hil[:-2].strip(), "low"
        note = ""
        if "[" in tgl and tgl.endswith("]"):
            tgl, note = tgl[:-1].split("[", 1)
            tgl, note = tgl.strip(), note.strip()
        yield {"tagalog": tgl, "hiligaynon": hil, "category": category, "note": note, "confidence": confidence}

    for tgl_forms, hil_forms in VERB_ASPECTS:
        for aspect, t, h in zip(ASPECT_NAMES, tgl_forms, hil_forms):
            yield {"tagalog": t, "hiligaynon": h, "category": "verbs (conjugated)",
                   "note": aspect, "confidence": "normal"}


